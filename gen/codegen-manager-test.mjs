// Emits test/ManagerParity.t.sol: replays vectors through the real PoolManager + routers,
// proving the Oracle (which calls Pool library directly) reproduces PoolManager behaviour.
import { readFileSync, writeFileSync } from "node:fs";
const [file, n] = [process.argv[2] ?? "vectors/swaps.json", Number(process.argv[3] ?? 300)];
const vs = JSON.parse(readFileSync(file)).vectors.filter((v) => !v.expect.revert && v.swap.lpFeeOverride === 0).slice(0, n);
const lines = vs.map((v, i) => {
  const p = v.pool, s = v.swap, e = v.expect;
  const pos = p.positions.map((q) => `P(${q.tickLower}, ${q.tickUpper}, int128(${q.liquidity}))`).join(", ");
  return `    function test_v${String(i).padStart(4,'0')}() public {
        _v(${i}, V(${p.tickSpacing}, ${p.lpFee}, ${(p.protocolFeeOneForZero << 12) | p.protocolFeeZeroForOne}, ${p.sqrtPriceX96}, ${s.zeroForOne}, int256(${s.amountSpecified}), ${s.sqrtPriceLimitX96}, int128(${e.amount0}), int128(${e.amount1}), ${e.sqrtPriceX96}, int24(${e.tick}), ${e.liquidity}), _ps(${p.positions.length}, [${pos}${", P(0,0,0)".repeat(6 - p.positions.length)}]));
    }`;
});
writeFileSync("test/ManagerParity.t.sol", `// SPDX-License-Identifier: MIT
// GENERATED by gen/codegen-manager-test.mjs from ${file} — do not edit.
pragma solidity 0.8.26;

import {ParityBase} from "./ParityBase.sol";

contract ManagerParityTest is ParityBase {
${lines.join("\n")}
}
`);
console.log("wrote", vs.length, "vectors");
